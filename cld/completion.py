"""`cld completion bash`: print a bash completion script for cld.

Generated from the live argparse parser, so subcommands, flags and choices can
never drift from what cld actually accepts. Purely local: no connection, no
clouds.yaml secret is read (only the entry *names*, parsed by awk in the shell
at TAB time), nothing is written to the audit log.

Completes for `cld`, `cld.py` / `./cld.py` / any path ending in cld.py, and
`python3 cld.py ...` / `python3 -m cld ...`. For python/python3 the script
chains to whatever completion was registered before it, so ordinary
`python3 <TAB>` keeps working.
"""

import argparse

# Flags whose value is a local file path.
_FILE_DESTS = {"save_answers", "non_interactive"}

_TEMPLATE = r'''# bash completion for cld -- generated by `cld completion bash`; regenerate
# after upgrading cld rather than editing by hand.

_cld_clouds() {
    # Entry names from the first readable clouds.yaml, in cld's lookup order
    # (keep in sync with cloud.CLOUDS_PATHS). Reads names only (the keys one
    # level under `clouds:`), never values.
    local f
    for f in "$HOME/.config/openstack/clouds.yaml" /etc/openstack/clouds.yaml \
             "$PWD/clouds.yaml"; do
        [[ -r $f ]] || continue
        awk '/^clouds:[[:space:]]*$/ {inside = 1; next}
             inside && /^[^[:space:]#]/ {exit}
             inside && /^[[:space:]]+[^[:space:]#]/ {
                 match($0, /^[[:space:]]+/)
                 if (!indent) indent = RLENGTH
                 if (RLENGTH == indent) {
                     name = substr($0, RLENGTH + 1); sub(/:.*/, "", name)
                     gsub(/["\047]/, "", name); print name
                 }
             }' "$f"
        return
    done
}

_cld_fallback() {
    # Not a cld invocation (e.g. plain `python3 foo.py`): hand over to the
    # completion python3 had before cld was sourced, else complete filenames.
    if [[ -n $_cld_prev_python_func ]] && declare -F "$_cld_prev_python_func" >/dev/null; then
        "$_cld_prev_python_func" "$@"
    else
        compopt -o default 2>/dev/null
        COMPREPLY=()
    fi
}

_cld() {
    local start
    case ${COMP_WORDS[0]##*/} in
        python|python3|python3.*)
            if [[ ${COMP_WORDS[1]} == *cld.py ]]; then
                start=2
            elif [[ ${COMP_WORDS[1]} == -m && ${COMP_WORDS[2]} == cld ]]; then
                start=3
            else
                _cld_fallback "$@"; return
            fi ;;
        *) start=1 ;;
    esac
    if (( COMP_CWORD < start )); then
        _cld_fallback "$@"; return
    fi

    local cur=${COMP_WORDS[COMP_CWORD]} prev=${COMP_WORDS[COMP_CWORD-1]}
    # `--cloud=ad<TAB>`: '=' is a word break, so the flag sits two words back.
    if [[ $cur == = ]]; then
        cur=
    fi
    if [[ $prev == = ]]; then
        prev=${COMP_WORDS[COMP_CWORD-2]}
    fi

    if (( COMP_CWORD == start )) && [[ $cur != -* ]]; then
        COMPREPLY=($(compgen -W "@SUBCOMMANDS@" -- "$cur"))
        return
    fi

    # A bare invocation or leading flag means createvm (see cli.main).
    local sub=${COMP_WORDS[start]}
    case " @SUBCOMMANDS@ " in
        *" $sub "*) ;;
        *) sub=createvm ;;
    esac

    case "$sub $prev" in
@VALUE_CASES@
    esac

    if [[ $cur == -* ]]; then
        case $sub in
@FLAG_CASES@
        esac
        return
    fi

    case $sub in
@POSITIONAL_CASES@
    esac
}

if [[ -z ${_cld_prev_python_func+set} ]]; then
    # Capture python3's own completion (loading it lazily first if
    # bash-completion is present) so _cld_fallback can chain to it.
    _cld_prev_python_func=
    if ! complete -p python3 >/dev/null 2>&1 && declare -F _completion_loader >/dev/null; then
        _completion_loader python3 2>/dev/null
    fi
    _cld_spec=$(complete -p python3 2>/dev/null)
    if [[ $_cld_spec =~ -F\ ([^ ]+) && ${BASH_REMATCH[1]} != _cld ]]; then
        _cld_prev_python_func=${BASH_REMATCH[1]}
    fi
    unset _cld_spec
fi
complete -F _cld cld cld.py python python3
'''


def _subparsers(parser):
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action.choices
    return {}


def _words(items):
    return " ".join(sorted(items))


def bash_script(parser):
    subs = _subparsers(parser)
    value_cases, flag_cases, positional_cases = [], [], []
    for name, sp in subs.items():
        flags = []
        for a in sp._actions:
            if not a.option_strings:
                if a.choices:
                    positional_cases.append(
                        f'        {name}) COMPREPLY=($(compgen -W "{_words(map(str, a.choices))}"'
                        f' -- "$cur")) ;;')
                continue
            flags += a.option_strings
            if a.nargs == 0:
                continue  # store_true / help: takes no value
            pattern = "|".join(f'"{name} {o}"' for o in a.option_strings)
            if a.dest == "cloud" and name != "init":  # init --cloud names a NEW entry
                body = 'COMPREPLY=($(compgen -W "$(_cld_clouds)" -- "$cur"))'
            elif a.choices:
                body = f'COMPREPLY=($(compgen -W "{_words(map(str, a.choices))}" -- "$cur"))'
            elif a.dest in _FILE_DESTS:
                body = 'compopt -o filenames 2>/dev/null; COMPREPLY=($(compgen -f -- "$cur"))'
            else:
                body = "COMPREPLY=()"  # IDs, sizes, names: nothing to offer offline
            value_cases.append(f"        {pattern}) {body}; return ;;")
        flag_cases.append(
            f'            {name}) COMPREPLY=($(compgen -W "{_words(flags)}" -- "$cur")) ;;')

    return (_TEMPLATE
            .replace("@SUBCOMMANDS@", _words(subs))
            .replace("@VALUE_CASES@", "\n".join(value_cases))
            .replace("@FLAG_CASES@", "\n".join(flag_cases))
            .replace("@POSITIONAL_CASES@", "\n".join(positional_cases)))
